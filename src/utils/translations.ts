export const kurdishDigits = ['٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩'];

export function toKurdishDigits(input: string | number): string {
  const str = String(input);
  return str.replace(/\d/g, (d) => kurdishDigits[parseInt(d, 10)]);
}

export function toStandardDigits(input: string): string {
  let res = input;
  for (let i = 0; i < 10; i++) {
    res = res.replaceAll(kurdishDigits[i], String(i));
  }
  return res;
}

